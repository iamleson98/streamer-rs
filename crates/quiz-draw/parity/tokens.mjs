// Writes `src/tokens.rs`: the colours of the player's quiz screens as Chromium paints them, read from the
// real CSS (the bundle's style sheet) so none is typed in by hand. Each is a class on a probe element and the
// property that carries the colour; a class the player's CSS does not have fails (it would read transparent).
//   node tokens.mjs BUNDLE_DIR OUT.rs
//   node tokens.mjs --check BUNDLE_DIR OUT.rs
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright-core';

const args = process.argv.slice(2);
const check = args[0] === '--check';
const [bundle, out] = check ? args.slice(1) : args;
if (!out) throw new Error('usage: node tokens.mjs [--check] BUNDLE_DIR OUT.rs');

const BG = 'backgroundColor';
const TXT = 'color';
const BORDER = 'borderTopColor';
const RING = '--tw-ring-color';
const FROM = '--tw-gradient-from';
const TO = '--tw-gradient-to';

// [rust name, class (with the classes that make the property apply), property]
const tokens = [
	['BACKGROUND', 'bg-background', BG],
	['FOREGROUND', 'text-foreground', TXT],
	['CARD', 'bg-card', BG],
	['BORDER', 'border-border border', BORDER],
	['MUTED', 'bg-muted', BG],
	['MUTED_60', 'bg-muted/60', BG],
	['MUTED_50', 'bg-muted/50', BG],
	['MUTED_FOREGROUND', 'text-muted-foreground', TXT],
	['PRIMARY', 'text-primary', TXT],
	['PRIMARY_10', 'bg-primary/10', BG],
	['PRIMARY_FOREGROUND', 'text-primary-foreground', TXT],
	['GREEN_600', 'text-green-600', TXT],
	['AMBER_600_TEXT', 'text-amber-600', TXT],
	['RED_700', 'text-red-700', TXT],
	['RED_500', 'bg-red-500', BG],
	['AMBER_50', 'bg-amber-50', BG],
	['AMBER_100', 'bg-amber-100', BG],
	['AMBER_950', 'text-amber-950', TXT],
	['AMBER_500', 'border-amber-500 border', BORDER],
	['AMBER_400', 'fill-amber-400', 'fill'],
	['AMBER_500_TEXT', 'text-amber-500', TXT],
	['SLATE_100', 'bg-slate-100', BG],
	['SLATE_500', 'bg-slate-500', BG],
	['AMBER_600', 'bg-amber-600', BG],
	['ORANGE_800', 'bg-orange-800', BG],
	['GREEN_500', 'bg-green-500', BG],
	['PRIMARY_RING_30', 'ring-primary/30 ring-2', RING],
	...[
		['red', 500, 600],
		['blue', 500, 600],
		['amber', 500, 600],
		['green', 500, 600],
		['violet', 500, 600],
		['cyan', 500, 600],
		['pink', 500, 600]
	].flatMap(([hue, bg, ring], i) => [
		[`DISC_${i}_BG`, `bg-${hue}-${bg}/${hue === 'amber' ? 25 : 20}`, BG],
		[`DISC_${i}_RING`, `ring-${hue}-${ring}/40 ring-2`, RING]
	]),
	...[
		['red-600', 'rose-700'],
		['blue-600', 'indigo-700'],
		['orange-700', 'amber-700'],
		['emerald-700', 'green-700'],
		['violet-600', 'purple-700'],
		['cyan-700', 'sky-700']
	].flatMap(([from, to], i) => [
		[`TILE_${i}_FROM`, `bg-linear-to-br from-${from} to-${to}`, FROM],
		[`TILE_${i}_TO`, `bg-linear-to-br from-${from} to-${to}`, TO]
	]),
	...[
		'orange-500',
		'amber-600',
		'green-600',
		'lime-500',
		'violet-500',
		'blue-700',
		'yellow-800',
		'sky-500',
		'pink-500',
		'yellow-400',
		'red-500',
		'slate-500'
	].map((c, i) => [`CHARACTER_${i}_RING`, `ring-${c} ring-2`, RING])
];

const css = readFileSync(`${bundle}/harness.css`, 'utf8');
const browser = await chromium.launch();
let rows;
try {
	const page = await browser.newPage();
	await page.setContent(`<style>${css}</style><body></body>`);
	rows = await page.evaluate((list) => {
		const canvas = document.createElement('canvas');
		canvas.width = canvas.height = 1;
		const ctx = canvas.getContext('2d', { willReadFrequently: true });
		return list.map(([name, cls, prop]) => {
			const el = document.createElement('div');
			el.className = cls;
			document.body.append(el);
			const s = getComputedStyle(el);
			const value = (prop.startsWith('--') ? s.getPropertyValue(prop) : s[prop]).trim();
			el.remove();
			if (!value || value === 'rgba(0, 0, 0, 0)') throw new Error(`${name}: the class ${cls} gives no colour (${prop})`);
			// The alpha is read from the string; the colour is painted opaque on a canvas to get Chromium's own sRGB.
			const m = value.match(/\/\s*([\d.]+)(%?)\s*\)$/);
			const alpha = m ? (m[2] ? Number(m[1]) / 100 : Number(m[1])) : 1;
			const opaque = m ? value.replace(/\s*\/\s*[\d.]+%?\s*\)$/, ')') : value;
			ctx.clearRect(0, 0, 1, 1);
			ctx.fillStyle = '#000';
			ctx.fillStyle = opaque;
			ctx.fillRect(0, 0, 1, 1);
			const [r, g, b] = ctx.getImageData(0, 0, 1, 1).data;
			return { name, r, g, b, alpha, value };
		});
	}, tokens);
} finally {
	await browser.close();
}

const rust = `//! The colours of the player's quiz screens, as Chromium paints them. Generated by
//! \`parity/tokens.mjs\` from the player's own CSS (never edited by hand): \`node tokens.mjs --check\` fails when
//! it is out of date. The light theme: the render page never adds \`.dark\`.

use crate::color::Rgba;

${rows
	.map((r) => `/// \`${r.value}\`\npub const ${r.name}: Rgba = Rgba::new(${r.r}, ${r.g}, ${r.b}, ${Number.isInteger(r.alpha) ? r.alpha.toFixed(1) : r.alpha});`)
	.join('\n')}
`;
if (check) {
	if (readFileSync(out, 'utf8') !== rust) {
		console.error(`${out} is out of date: run node tokens.mjs`);
		process.exit(1);
	}
} else writeFileSync(out, rust);
console.log(`${rows.length} colours`);
