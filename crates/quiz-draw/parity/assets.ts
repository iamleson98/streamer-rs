// Writes `src/art_data.rs`: the pictures of the quiz screens as plain SVG text, taken from the player's own
// files (the characters and the coin of Quest, written out as markup in two Svelte components; the icons
// of `@lucide/svelte`, which keep their shapes as data), so none is redrawn by hand.
//   bun assets.ts OUT.rs
//   bun assets.ts --check OUT.rs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../lesson-replay/', import.meta.url).pathname;
const args = Bun.argv.slice(2);
const check = args[0] === '--check';
const out = check ? args[1] : args[0];
if (!out) throw new Error('usage: bun assets.ts [--check] OUT.rs');
const INK = '#1e293b';

/** The markup between `<svg ...>` and `</svg>` of a Svelte component, with its `{INK}` filled in. */
const svgOf = (source: string) => {
	const m = source.match(/<svg\b([\s\S]*?)>([\s\S]*)<\/svg>/);
	if (!m) throw new Error('no svg');
	const attrs = (name: string) => m[1].match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
	const stroke = m[1].match(/stroke=\{INK\}/) ? INK : attrs('stroke');
	return { head: `viewBox="${attrs('viewBox')}" fill="${attrs('fill')}" stroke="${stroke}" stroke-width="${attrs('stroke-width')}" stroke-linejoin="${attrs('stroke-linejoin')}" stroke-linecap="${attrs('stroke-linecap')}"`, body: m[2] };
};
const clean = (body: string) =>
	body
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/=\{INK\}/g, `="${INK}"`)
		.replace(/\s+/g, ' ')
		.trim();

const art = readFileSync(`${root}src/lib/replay/quiz/quest/components/character-art.svelte`, 'utf8');
const { head, body } = svgOf(art.slice(art.indexOf('<svg')));
const parts = body.split(/\{:else if id === \d+\}|\{:else\}/);
const first = parts[0].replace(/\{#if id === 0\}/, '');
const characters = [first, ...parts.slice(1)].map((p) => p.replace(/\{\/if\}/, ''));
if (characters.length !== 12) throw new Error(`${characters.length} characters`);

const glyph = readFileSync(`${root}src/lib/replay/quiz/quest/components/glyph.svelte`, 'utf8');
const g = svgOf(glyph.slice(glyph.indexOf('<svg')));
const coin = g.body.match(/\{#if kind === 'coin'\}([\s\S]*?)\{:else if kind === 'jackpot'\}/)![1];

const icons = ['users', 'triangle', 'diamond', 'circle', 'square', 'star', 'hexagon', 'check', 'crown', 'swords'].map((name) => {
	const src = readFileSync(`${root}node_modules/@lucide/svelte/dist/icons/${name}.svelte`, 'utf8');
	const data = JSON.parse(src.match(/const iconData = (\{.*\});/)![1]) as { node: [string, Record<string, string>][] };
	const shapes = data.node.map(([tag, a]) => `<${tag} ${Object.entries(a).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
	return [name, `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`];
});

const lit = (s: string) => `r##"${s}"##`;
const rust = `//! The pictures of the quiz screens as SVG text, generated by \`parity/assets.ts\` from the player's own files
//! (never edited by hand): \`bun assets.ts --check\` fails when it is out of date.

/// The twelve characters of Quest (\`quiz/quest/components/character-art.svelte\`).
#[rustfmt::skip]
pub const CHARACTERS: [&str; 12] = [
${characters.map((c) => `    ${lit(`<svg ${head}>${clean(c)}</svg>`)},`).join('\n')}
];

/// The coin of Quest's board (\`glyph.svelte\`).
#[rustfmt::skip]
pub const COIN: &str = ${lit(`<svg ${g.head}>${clean(coin)}</svg>`)};

/// Icons of \`@lucide/svelte\` the screens use, by name.
#[rustfmt::skip]
pub const ICONS: [(&str, &str); ${icons.length}] = [
${icons.map(([n, s]) => `    ("${n}", ${lit(s)}),`).join('\n')}
];
`;
if (check) {
	if (readFileSync(out, 'utf8') !== rust) {
		console.error(`${out} is out of date: run bun assets.ts`);
		process.exit(1);
	}
} else writeFileSync(out, rust);
console.log(`${characters.length} characters, ${icons.length} icons`);
